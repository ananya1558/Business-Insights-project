-- ====================================================================================================
-- REQUEST 4: STORED PROCEDURE - MONTHLY GROSS SALES BY CUSTOMER & MARKET
-- Business Need: Parameterized reporting allowing product owners to query any customer in any market.
-- ====================================================================================================

DROP PROCEDURE IF EXISTS get_monthly_gross_sales_for_customer;

DELIMITER $$
CREATE PROCEDURE get_monthly_gross_sales_for_customer(
    IN in_customer_name VARCHAR(100),
    IN in_market VARCHAR(50)
)
BEGIN
    SELECT 
        s.date,
        c.customer,
        c.market,
        ROUND(SUM(s.sold_quantity * g.gross_price), 2) AS gross_total_price
    FROM fact_sales_monthly s
    INNER JOIN dim_customer c 
        ON c.customer_code = s.customer_code
    INNER JOIN fact_gross_price g 
        ON g.product_code = s.product_code 
        AND g.fiscal_year = get_fiscal_year(s.date)
    WHERE c.customer LIKE CONCAT('%', in_customer_name, '%')
      AND (in_market IS NULL OR in_market = '' OR c.market = in_market)
    GROUP BY s.date, c.customer, c.market
    ORDER BY s.date ASC;
END $$
DELIMITER ;

