-- ====================================================================================================
-- 2. USER DEFINED FUNCTION: GET_FISCAL_QUARTER
-- Determines Fiscal Quarter for AtliQ calendar:
-- Q1: Sep, Oct, Nov | Q2: Dec, Jan, Feb | Q3: Mar, Apr, May | Q4: Jun, Jul, Aug
-- ====================================================================================================

DROP FUNCTION IF EXISTS get_fiscal_quarter;

DELIMITER $$
CREATE FUNCTION get_fiscal_quarter(calendar_date DATE)
RETURNS VARCHAR(2)
DETERMINISTIC
READS SQL DATA
BEGIN
    DECLARE m INT;
    DECLARE fq VARCHAR(2);
    SET m = MONTH(calendar_date);
    
    CASE 
        WHEN m IN (9, 10, 11) THEN SET fq = 'Q1';
        WHEN m IN (12, 1, 2)  THEN SET fq = 'Q2';
        WHEN m IN (3, 4, 5)   THEN SET fq = 'Q3';
        ELSE SET fq = 'Q4';
    END CASE;
    
    RETURN fq;
END $$
DELIMITER ;


-- ====================================================================================================
-- REQUEST 1: CROMA INDIA PRODUCT-WISE SALES REPORT FOR FISCAL YEAR 2021
-- Business Need: Aggregated monthly report at product code level for Croma India to track unit economics.
-- ====================================================================================================

SELECT 
    s.date,
    get_fiscal_quarter(s.date) AS fiscal_quarter,
    s.product_code,
    p.product,
    p.variant,
    s.sold_quantity,
    g.gross_price,
    ROUND(g.gross_price * s.sold_quantity, 2) AS gross_price_total
FROM fact_sales_monthly s
INNER JOIN dim_product p 
    ON p.product_code = s.product_code
INNER JOIN fact_gross_price g 
    ON g.product_code = s.product_code 
    AND g.fiscal_year = get_fiscal_year(s.date)
WHERE s.customer_code IN (
    SELECT customer_code 
    FROM dim_customer 
    WHERE customer LIKE '%Croma%' AND market = 'India'
)
AND get_fiscal_year(s.date) = 2021
ORDER BY s.date ASC, gross_price_total DESC;


