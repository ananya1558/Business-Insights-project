USE gdb041;

-- ====================================================================================================
-- 1. USER DEFINED FUNCTION: GET_FISCAL_YEAR
-- AtliQ Hardware's fiscal year starts from September (Month 9).
-- Formula: Fiscal Year = Calendar Year of (Date + 4 Months)
-- Example: September 2020 + 4 months = January 2021 -> Fiscal Year 2021
-- ====================================================================================================

DROP FUNCTION IF EXISTS get_fiscal_year;

DELIMITER $$
CREATE FUNCTION get_fiscal_year(calendar_date DATE)
RETURNS INT
DETERMINISTIC
READS SQL DATA
BEGIN
    DECLARE fiscal_year INT;
    SET fiscal_year = YEAR(DATE_ADD(calendar_date, INTERVAL 4 MONTH));
    RETURN fiscal_year;
END $$
DELIMITER ;

