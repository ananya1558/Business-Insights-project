-- ====================================================================================================
-- REQUEST 5: STORED PROCEDURE - MARKET BADGE CLASSIFICATION (GOLD / SILVER)
-- Business Need: Classify markets into Gold (> $5M Gross Sales) or Silver (<= $5M Gross Sales)
-- Fully compliant with MySQL ONLY_FULL_GROUP_BY standards.
-- ====================================================================================================

DROP PROCEDURE IF EXISTS get_market_badge;

DELIMITER $$
CREATE PROCEDURE get_market_badge(
    IN in_market VARCHAR(50),
    IN in_fiscal_year INT,
    OUT out_badge VARCHAR(10)
)
BEGIN
    DECLARE total_gross_sales DECIMAL(15,2);
    
    SELECT 
        COALESCE(SUM(s.sold_quantity * g.gross_price), 0) INTO total_gross_sales
    FROM fact_sales_monthly s
    INNER JOIN dim_customer c 
        ON c.customer_code = s.customer_code
    INNER JOIN fact_gross_price g 
        ON g.product_code = s.product_code 
        AND g.fiscal_year = get_fiscal_year(s.date)
    WHERE c.market = in_market
      AND get_fiscal_year(s.date) = in_fiscal_year;
      
    IF total_gross_sales > 5000000 THEN
        SET out_badge = 'GOLD';
    ELSE
        SET out_badge = 'SILVER';
    END IF;
    
    -- Also return a result set for ad-hoc inspection
    SELECT 
        in_market AS market,
        in_fiscal_year AS fiscal_year,
        ROUND(total_gross_sales / 1000000, 2) AS total_gross_sales_mln,
        out_badge AS market_badge;
END $$
DELIMITER ;

